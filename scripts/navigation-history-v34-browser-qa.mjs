import assert from 'node:assert/strict';
import {chromium,webkit} from 'playwright';
const engine=process.env.FISH_TARGET_QA_ENGINE==='webkit'?webkit:chromium;
const browser=await engine.launch();
const base=process.env.FISH_TARGET_QA_URL||'http://127.0.0.1:4173/dist/';
try{
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',error=>errors.push(String(error)));
 const settled=()=>page.waitForFunction(()=>globalThis.FISH_TARGET_NAVIGATION&&!FISH_TARGET_NAVIGATION.isRestoring());
 const view=async name=>{await page.waitForFunction(name=>document.querySelector('.view.on')?.id===name,name);await settled()};
 await page.goto(base);await settled();
 const initial=await page.evaluate(()=>history.length);
 await page.locator('#q').fill('シーバス');
 await page.locator('button.fish[data-fish="シーバス"]').click();await view('result');
 assert.equal(await page.evaluate(()=>history.length),initial+1);
 await page.locator('#ux23MethodChange').click();
 const method=page.locator('[data-method-id]').last();await method.click();
 const selected=await method.getAttribute('data-method-id');
 await page.locator('#fieldModeBtn').click();await view('fieldmode');
 await page.goBack();await view('result');
 assert.equal(await page.locator('[data-method-id].on').getAttribute('data-method-id'),selected);
 await page.goForward();await view('fieldmode');
 assert.equal(await page.locator('#fmFish').innerText(),'シーバス');
 await page.locator('#fieldBack').click();await view('result');
 await page.locator('#back').click();await view('home');
 assert.equal(await page.locator('#q').inputValue(),'シーバス');
 await page.goForward();await view('result');
 await page.locator('#tackleEditFromResult').click();
 await page.waitForFunction(()=>FISH_TARGET_NAVIGATION.getState()?.modal==='tackle');
 await page.locator('[data-kind="rod"] [data-mode="manual"]').click();
 await page.locator('#rodName').fill('未登録の入力');
 await page.goBack();await settled();
 assert.equal(await page.locator('#tackleSheet').isHidden(),true);
 await page.goForward();await settled();
 assert.equal(await page.locator('#tackleSheet').isVisible(),true);
 assert.equal(await page.locator('#rodName').inputValue(),'未登録の入力');
 await page.locator('#tackleClose').click();await settled();
 await page.waitForFunction(()=>FISH_TARGET_NAVIGATION.getState()?.modal===null);
 await page.reload();await settled();await view('result');
 await page.waitForFunction(()=>document.getElementById('rname')?.textContent?.trim()==='シーバス');
 assert.equal((await page.locator('#rname').textContent()||'').trim(),'シーバス');
 assert.equal(await page.locator('[data-method-id].on').getAttribute('data-method-id'),selected);
 await page.locator('#back').click();await view('home');
 await page.locator('#appTabBarV26 [data-app-tab="conditions"]').click();await view('conditions');
 await page.locator('#conditionsPackBtn').click();
 await page.waitForFunction(()=>FISH_TARGET_NAVIGATION.getState()?.modal==='pack');
 await page.goBack();await settled();
 assert.equal(await page.locator('#packStandaloneV30').isHidden(),true);
 await page.goForward();await settled();
 assert.equal(await page.locator('#packStandaloneV30').isVisible(),true);
 await page.locator('#packStandaloneCloseV30').click();await settled();
 await page.waitForFunction(()=>FISH_TARGET_NAVIGATION.getState()?.modal===null);
 await page.locator('#appTabBarV26 [data-app-tab="home"]').click();await view('home');
 await page.evaluate(()=>history.replaceState({fishTargetNavigationV34:{version:1,view:'unknown'}},''));
 await page.reload();await settled();await view('home');
 // The app must allow leaving its initial entry, without a back-button trap.
 const other=await browser.newPage();
 await other.goto('about:blank');await other.goto(base);
 await other.waitForFunction(()=>Boolean(globalThis.FISH_TARGET_NAVIGATION));
 await other.goBack();assert.equal(other.url(),'about:blank');await other.close();
 assert.deepEqual(errors,[]);
 console.log('NAVIGATION_HISTORY_V34_BROWSER_QA_PASS',engine.name());
}finally{await browser.close()}
